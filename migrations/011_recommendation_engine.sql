CREATE TABLE IF NOT EXISTS metadata.table_recommendations (
    recommendation_id       SERIAL          PRIMARY KEY,
    table_id                INTEGER         NOT NULL REFERENCES metadata.db_tables(table_master_key) ON DELETE CASCADE,
    recommendation_type     VARCHAR(50)     NOT NULL, -- e.g. 'CDC_STRATEGY', 'PARTITIONING'
    recommended_value       VARCHAR(200)    NOT NULL, -- e.g. 'LAST_UPDATE_DATE'
    recommended_type        VARCHAR(50)     NOT NULL, -- 'TIMESTAMP', 'SEQUENCE', 'SCN', 'NONE'
    confidence_score        INTEGER         NOT NULL, -- 0 to 100
    confidence_breakdown    JSONB           NOT NULL, -- {"timestamp_type":30, "indexed":20, "not_null":10, "fresh_stats":5}
    performance_risk        VARCHAR(20)     NOT NULL, -- 'LOW', 'MEDIUM', 'HIGH'
    correctness_risk        VARCHAR(20)     NOT NULL, -- 'LOW', 'MEDIUM', 'HIGH'
    recommendation_status   VARCHAR(30)     DEFAULT 'GENERATED', -- 'GENERATED', 'OBSOLETE'
    generated_by_engine     VARCHAR(100)    DEFAULT 'MetadataDiscoveryEngine_v1.0',
    generated_at            TIMESTAMP       NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_recs_table_status 
    ON metadata.table_recommendations (table_id, recommendation_status);

CREATE INDEX IF NOT EXISTS idx_recs_status 
    ON metadata.table_recommendations (recommendation_status);

COMMENT ON TABLE metadata.table_recommendations IS 'Pluggable recommendations generated by Phase 2 Discovery Engine. Never modifies execution tables directly.';
